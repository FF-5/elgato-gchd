enum { GCHD_RES_NTSC=1, GCHD_RES_PAL=2, GCHD_RES_720=3, GCHD_RES_1080=4 };

static int gchd_resolution(struct gchd *d)
{
 if (d->input_width == 1920) return GCHD_RES_1080;
 if (d->input_width == 1280) return GCHD_RES_720;
 if (d->input_height == 576) return GCHD_RES_PAL;
 if (d->input_height == 480) return GCHD_RES_NTSC;
 return 0;
}

static int gchd_mail_read_discard(struct gchd *d, u8 port, u8 len)
{
 u8 buf[56];
 if (len > sizeof(buf)) return -EINVAL;
 return gchd_mail_read(d, port, buf, len);
}

static int gchd_read_9dcd(struct gchd *d, u8 index, u8 *value)
{
 u8 cmd[3]={0x9d,0xcd,index};
 int r=gchd_mail_write(d,0x33,cmd,3);
 if (r) return r;
 return gchd_mail_read(d,0x33,value,1);
}

static int gchd_poll_9989ed(struct gchd *d)
{
 u8 cmd[3]={0x99,0x89,0xed}, v;
 int r;
 do {
  r=gchd_mail_write(d,0x33,cmd,3); if(r) return r;
  r=gchd_mail_read(d,0x33,&v,1); if(r) return r;
 } while (!(v & 0x40));
 return 0;
}

static int gchd_read_9989ec(struct gchd *d, unsigned int count)
{
 u8 cmd[3]={0x99,0x89,0xec}, v;
 unsigned int i;
 int r;
 for(i=0;i<count;i++){
  r=gchd_mail_write(d,0x33,cmd,3); if(r) return r;
  r=gchd_mail_read(d,0x33,&v,1); if(r) return r;
 }
 return 0;
}

#define GCHD_MW(d,p,...) do { u8 __b[]={__VA_ARGS__}; int __r=gchd_mail_write((d),(p),__b,sizeof(__b)); if(__r) return __r; } while(0)
#define GCHD_MR(d,p,n) do { int __r=gchd_mail_read_discard((d),(p),(n)); if(__r) return __r; } while(0)
#define GCHD_MR_IN(d,p,b,n) do { int __r=gchd_mail_read((d),(p),(b),(n)); if(__r) return __r; } while(0)
#define GCHD_MR1(d,p,v) do { u8 __x; int __r=gchd_mail_read((d),(p),&__x,1); if(__r) return __r; (v)=__x; } while(0)
#define GCHD_R9(d,i) do { u8 __x; int __r=gchd_read_9dcd((d),(i),&__x); if(__r) return __r; } while(0)
#define GCHD_POLL(d) do { int __r=gchd_poll_9989ed((d)); if(__r) return __r; } while(0)
#define GCHD_READ_EC(d,n) do { int __r=gchd_read_9989ec((d),(n)); if(__r) return __r; } while(0)

