/*
 * One measurement batch for retries after connector preparation. This path
 * never repeats the long encoder-start sequence or timing-dependent setup.
 */
int gchd_probe_video_source(struct gchd *d)
{
 u32 sum6665 = 0, sum6463 = 0, count6665 = 0, count6463 = 0;
 u32 value6665, value6463;
 int r;

 WRITE_ONCE(d->signal_present, false);
 if (d->input == 0) {
  r = gchd_hdmi_read_signal(d, &sum6463, &count6463,
                            &sum6665, &count6665, &d->rgb_input);
  if (r) return r;
  value6665 = sum6665 / count6665;
  value6463 = sum6463 / count6463;
  dev_info(&d->intf->dev,
           "gchd-diag detect HDMI: samples6665=%u avg6665=0x%04x samples6463=%u avg6463=0x%04x rgb=%u\n",
           count6665, value6665, count6463, value6463, d->rgb_input);
  if (!gchd_hdmi_timing_valid(value6463) ||
      abs((int)value6665 - 0xad4d) < 10)
   return -ENOLINK;
  if (value6463 >= 0xb6cd && value6463 <= 0xb6e1) {
   d->input_width=1920; d->input_height=1080; d->input_interlaced=false;
  } else if (value6463 >= 0xb077 && value6463 <= 0xb08b) {
   d->input_width=1920; d->input_height=1080; d->input_interlaced=true;
  } else if (value6463 >= 0xb052 && value6463 <= 0xb066) {
   d->input_width=1280; d->input_height=720; d->input_interlaced=false;
  } else {
   d->input_width=720;
   d->input_height=(value6665 >= 0xbb6b && value6665 <= 0xbb7f) ? 576 : 480;
   d->input_interlaced=false;
  }
  d->input_fps_num=d->input_height==576 ? 50 : 60;
  d->input_fps_den=1;
 } else if (d->input == 1) {
  u8 hi, lo;
  u32 value6867;
  r = gchd_mail_write(d,GCHD_MAIL_PORT_SYSTEM,(u8[]){GCHD_CMD_REGISTER_READ,GCHD_CMD_REGISTER_READ_EXT,GCHD_VALUE_66},3); if(r)return r;
  r = gchd_mail_read(d,GCHD_MAIL_PORT_SYSTEM,&hi,1); if(r)return r;
  sum6665=(u32)hi<<8;
  r = gchd_mail_write(d,GCHD_MAIL_PORT_SYSTEM,(u8[]){GCHD_CMD_REGISTER_READ,GCHD_CMD_REGISTER_READ_EXT,GCHD_VALUE_65},3); if(r)return r;
  r = gchd_mail_read(d,GCHD_MAIL_PORT_SYSTEM,&lo,1); if(r)return r;
  sum6665|=lo;
  r = gchd_mail_write(d,GCHD_MAIL_PORT_SYSTEM,(u8[]){GCHD_CMD_REGISTER_READ,GCHD_CMD_REGISTER_READ_EXT,GCHD_VALUE_68},3); if(r)return r;
  r = gchd_mail_read(d,GCHD_MAIL_PORT_SYSTEM,&hi,1); if(r)return r;
  value6867=(u32)hi<<8;
  r = gchd_mail_write(d,GCHD_MAIL_PORT_SYSTEM,(u8[]){GCHD_CMD_REGISTER_READ,GCHD_CMD_REGISTER_READ_EXT,GCHD_VALUE_67},3); if(r)return r;
  r = gchd_mail_read(d,GCHD_MAIL_PORT_SYSTEM,&lo,1); if(r)return r;
  value6867|=lo;
  dev_info(&d->intf->dev,
           "gchd-diag detect component: raw6665=0x%04x raw6867=0x%04x\n",
           (u16)sum6665, (u16)value6867);
  if (!gchd_component_timing_valid(value6867) ||
      abs((int)sum6665-0xad4d)<10)
   return -ENOLINK;
  if (abs((int)value6867-0xbbf4)<10) {
   d->input_width=1920; d->input_height=1080; d->input_interlaced=false; d->input_fps_num=30;
  } else if (abs((int)value6867-0xa03d)<10) {
   d->input_width=1920; d->input_height=1080; d->input_interlaced=true; d->input_fps_num=60;
  } else if (abs((int)value6867-0xbf59)<10) {
   d->input_width=1280; d->input_height=720; d->input_interlaced=false; d->input_fps_num=60;
  } else if (abs((int)value6867-0xa6b7)<10) {
   d->input_width=720; d->input_height=576; d->input_interlaced=false; d->input_fps_num=50;
  } else if (abs((int)value6867-0x9ab9)<10) {
   d->input_width=720; d->input_height=576; d->input_interlaced=true; d->input_fps_num=50;
  } else if (abs((int)value6867-0xa150)<10) {
   d->input_width=720; d->input_height=480; d->input_interlaced=false; d->input_fps_num=60;
  } else {
   d->input_width=720; d->input_height=480; d->input_interlaced=true; d->input_fps_num=60;
  }
  d->input_fps_den=1;
 } else {
  u8 v;

  /*
   * Composite and S-video share the documented no-signal keep-alive loop.
   * Poll FA and F5 before the format/status probes; FA is the source-detect
   * candidate, while F5 is the companion sequence-read used by the device
   * during idle. Keep the two commands in this order.
   */
  r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM,
                      (u8[]){GCHD_CMD_QUERY_EXT,GCHD_CMD_QUERY_EXT,0xfa}, 3);
  if (r) return r;
  r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, &v, 1);
  if (r) return r;
  r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM,
                      (u8[]){GCHD_CMD_QUERY,GCHD_CMD_QUERY_EXT,0xf5}, 3);
  if (r) return r;
  r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, &v, 1);
  if (r) return r;

  /*
   * Prime the analog decoder before reading its NTSC/PAL family status.
   * The family nibble is not enough to distinguish 240p/288p from 480i/576i;
   * the later live-mode monitor handles the NTSC 240p transition.
   */
  r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){0x94,0x41,0x37}, 3);
  if (r) return r;
  r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){0x94,0x4a,0xaf}, 3);
  if (r) return r;
  r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){0x94,0x4b,0xaf}, 3);
  if (r) return r;
  r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){GCHD_CMD_QUERY_EXT,GCHD_CMD_QUERY_EXT,GCHD_QUERY_ENCODER_STATUS}, 3);
  if (r) return r;
  r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, &v, 1);
  if (r) return r;
  dev_info(&d->intf->dev,
           "gchd-diag detect %s: raw_status=0x%02x masked_mode=0x%01x\n",
           d->input == 2 ? "composite" : "s-video", v, v & 0x0f);
  v &= 0x0f;
  if (v == 6) {
   u8 mode;

   d->input_width=720; d->input_height=480;
   d->input_interlaced=true; d->input_fps_num=60;
   /* 0xCA is the decoder's authoritative 240p/480i lock indicator. */
   r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){GCHD_CMD_QUERY_EXT,GCHD_CMD_QUERY_EXT,GCHD_QUERY_ENCODER_CONFIG}, 3);
   if (r) return r;
   r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, &mode, 1);
   if (r) return r;
   /*
    * Start with the known-good 480i receiver/encoder setup, as in the
    * reference trace. A 240p lock is applied only after capture starts and
    * the live monitor sees 0x66; this avoids skipping the transition recipe
    * when 0x66 is already present during initial detection.
    */
   if (mode != GCHD_REPLY_STATUS_SVIDEO && mode != GCHD_REPLY_STATUS_COMPOSITE)
    dev_dbg(&d->intf->dev,
            "analog format status not locked yet: 0x%02x; starting in 480i\n",
            mode);
   dev_info(&d->intf->dev,
            "analog format initial status=0x%02x; starting in 480i\n",
            mode);
   d->input_interlaced = true;
  } else if (v == 7) {
   d->input_width=720; d->input_height=576;
   d->input_interlaced=true; d->input_fps_num=50;
  } else return -ENOLINK;
  d->input_fps_den=1;
 }
 WRITE_ONCE(d->signal_present,true);
 dev_info(&d->intf->dev,
          "gchd-diag detected input=%u mode=%ux%u fps=%u/%u interlaced=%u signal_present=%u\n",
          d->input, d->input_width, d->input_height, d->input_fps_num,
          d->input_fps_den, d->input_interlaced, d->signal_present);
 return 0;
}

