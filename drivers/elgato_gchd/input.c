 r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){GCHD_CMD_REGISTER_READ,GCHD_CMD_REGISTER_READ_EXT,GCHD_VALUE_63}, 3); if (r) return r;
 r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, &v, 1); if (r) return r; a |= v;
