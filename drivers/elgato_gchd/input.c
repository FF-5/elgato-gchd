struct gchd_mail_cmd {
 u8 port;
 u8 len;
 u8 data[8];
};

static int gchd_seq(struct gchd *d, const struct gchd_mail_cmd *s, size_t n)
{
 size_t i;
 int r;
 for (i = 0; i < n; ++i) {
  r = gchd_mail_write(d, s[i].port, s[i].data, s[i].len);
  if (r)
   return r;
 }
 return 0;
}

