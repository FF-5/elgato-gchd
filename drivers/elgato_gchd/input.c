static int gchd_encoder_start(struct gchd *d)
{
 u8 reply[3];
 int r, i;
 u32 state;

 /*
  * hw_init() has already completed the processor-state machine through the
  * second 0x27f97b.  configureDevice() enters the encoder bring-up here,
  * starting with the 0x5b polling phase.
  */
 for (i = 0; i < 5; ++i) {
  r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM,
                      (u8[]){GCHD_CMD_ENCODER_POLL,GCHD_CMD_ENCODER_POLL_EXT,GCHD_CMD_ENCODER_POLL_MODE,GCHD_CMD_ENCODER_POLL_ARG,GCHD_CMD_ENCODER_POLL_INITIAL}, 5);
  if (r) return r;
  r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, reply, 3);
  if (r) return r;
  r = gchd_enable_analog(d);
  if (r) return r;
  state = ((u32)reply[0] << 16) | ((u32)reply[1] << 8) | reply[2];
  if ((state & GCHD_REPLY_ENCODER_MASK) == GCHD_REPLY_ENCODER_ACTIVE)
   break;
 }

 r = gchd_do_enable(d, BIT(3), BIT(3));
 if (r) return r;

 /*
  * Turning on the encoder can temporarily return to 0x334455.  Keep polling
  * until the processor is back at 0x27f97b, as configureDevice() does.
  */
 for (i = 0; i < 1000; ++i) {
  r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM,
                      (u8[]){GCHD_CMD_ENCODER_POLL,GCHD_CMD_ENCODER_POLL_EXT,GCHD_CMD_ENCODER_POLL_MODE,GCHD_CMD_ENCODER_POLL_ARG,GCHD_CMD_ENCODER_POLL_CONTINUE}, 5);
  if (r) return r;
  r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, reply, 3);
  if (r) return r;
  state = ((u32)reply[0] << 16) | ((u32)reply[1] << 8) | reply[2];
  if (state == GCHD_REPLY_PROCESSOR_ACTIVE)
   break;
 }
 if (i == 1000)
  return -ETIMEDOUT;

 r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){0x28,0x28}, 2);
 if (r) return r;
 r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){GCHD_CMD_PROCESSOR_START,GCHD_CMD_QUERY_EXT,GCHD_CMD_PROCESSOR_START_ARG}, 3);
 if (r) return r;
 r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, reply, 1);
 if (r) return r;

 r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){0xdd,0xce,0x3f,0xb2}, 4);
 if (r) return r;
 r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, reply, 2);
 if (r) return r;

 r = gchd_do_enable(d, BIT(4), BIT(4));
 if (r) return r;

 for (i = 0; i < 1000; ++i) {
  r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){GCHD_CMD_ENCODER_STATUS,GCHD_CMD_ENCODER_STATUS_EXT,GCHD_CMD_ENCODER_STATUS_ARG}, 3);
  if (r) return r;
  r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, reply, 1);
  if (r) return r;
  if (reply[0] == GCHD_REPLY_ENCODER_READY)
   break;
 }
 if (i == 1000)
  return -ETIMEDOUT;

 r = gchd_do_enable(d, BIT(4), 0);
 if (r) return r;

 r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){GCHD_CMD_QUERY_EXT,GCHD_CMD_QUERY_EXT,GCHD_QUERY_ENCODER_INIT}, 3);
 if (r) return r;
 r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, reply, 1);
 if (r) return r;

 r = gchd_post_encoder_prefix(d);
 if (r) return r;

 r = gchd_post_encoder_sweep(d);
 if (r) return r;

 r = gchd_post_encoder_state(d);
 if (r) return r;

 r = gchd_transcoder_setup(d);
 if (r) return r;
 r = gchd_transcoder_output_enable(d, true);
 if (r) return r;

 return 0;
}

