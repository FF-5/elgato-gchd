int gchd_input_read_analog_mode(struct gchd *d, bool *interlaced)
{
 u8 status;
 int r;

 if (d->input < 2 || d->input_height != 480)
  return -EOPNOTSUPP;
 r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){GCHD_CMD_QUERY_EXT,GCHD_CMD_QUERY_EXT,GCHD_QUERY_ENCODER_CONFIG}, 3);
 if (r)
  return r;
 r = gchd_mail_read(d, GCHD_MAIL_PORT_SYSTEM, &status, 1);
 if (r)
  return r;

 /* FE is unlocked and EE is transitional: neither is a mode change. */
 if (status == GCHD_REPLY_STATUS_COMPOSITE)
  *interlaced = false;
 else if (status == GCHD_REPLY_STATUS_SVIDEO)
  *interlaced = true;
 else
  return -EAGAIN;
 return 0;
}

