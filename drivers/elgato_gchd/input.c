static int gchd_encoder_start(struct gchd *d)
{
 u8 reply[3];
 int r, i;
 u32 state;

 /*
  * hw_init() has already completed the processor-state machine through the
  * second 0x27f97b.  configureDevice() enters the encoder bring-up here,
  * starting with the 0x5b polling phase.
  */
 for (i = 0; i < 5; ++i) {
  r = gchd_mail_write(d, 0x33,
                      (u8[]){0xab,0xa9,0x0f,0xa4,0x5b}, 5);
  if (r) return r;
  r = gchd_mail_read(d, 0x33, reply, 3);
  if (r) return r;
  r = gchd_enable_analog(d);
  if (r) return r;
  state = ((u32)reply[0] << 16) | ((u32)reply[1] << 8) | reply[2];
  if ((state & 0xf8f0f0) == 0x78e040)
   break;
 }

 r = gchd_do_enable(d, BIT(3), BIT(3));
 if (r) return r;

 /*
  * Turning on the encoder can temporarily return to 0x334455.  Keep polling
  * until the processor is back at 0x27f97b, as configureDevice() does.
  */
 for (i = 0; i < 1000; ++i) {
  r = gchd_mail_write(d, 0x33,
                      (u8[]){0xab,0xa9,0x0f,0xa4,0x55}, 5);
  if (r) return r;
  r = gchd_mail_read(d, 0x33, reply, 3);
  if (r) return r;
  state = ((u32)reply[0] << 16) | ((u32)reply[1] << 8) | reply[2];
  if (state == 0x27f97b)
   break;
 }
 if (i == 1000)
  return -ETIMEDOUT;

 r = gchd_mail_write(d, 0x33, (u8[]){0x28,0x28}, 2);
 if (r) return r;
 r = gchd_mail_write(d, 0x33, (u8[]){0x29,0x89,0x5b}, 3);
 if (r) return r;
 r = gchd_mail_read(d, 0x33, reply, 1);
 if (r) return r;

 r = gchd_mail_write(d, 0x33, (u8[]){0xdd,0xce,0x3f,0xb2}, 4);
 if (r) return r;
 r = gchd_mail_read(d, 0x33, reply, 2);
 if (r) return r;

 r = gchd_do_enable(d, BIT(4), BIT(4));
 if (r) return r;

 for (i = 0; i < 1000; ++i) {
  r = gchd_mail_write(d, 0x33, (u8[]){0x43,0x23,0x84}, 3);
  if (r) return r;
  r = gchd_mail_read(d, 0x33, reply, 1);
  if (r) return r;
  if (reply[0] == 0xf7)
   break;
 }
 if (i == 1000)
  return -ETIMEDOUT;

 r = gchd_do_enable(d, BIT(4), 0);
 if (r) return r;

 r = gchd_mail_write(d, 0x33, (u8[]){0x89,0x89,0xfb}, 3);
 if (r) return r;
 r = gchd_mail_read(d, 0x33, reply, 1);
 if (r) return r;

 r = gchd_post_encoder_prefix(d);
 if (r) return r;

 r = gchd_post_encoder_sweep(d);
 if (r) return r;

 r = gchd_post_encoder_state(d);
 if (r) return r;

 r = gchd_transcoder_setup(d);
 if (r) return r;
 r = gchd_transcoder_output_enable(d, true);
 if (r) return r;

 r = gchd_input_finalize(d);
 if (r) return r;

 return 0;
}

static int gchd_read_9dcd(struct gchd *d, u8 index, u8 *value)
{
 u8 cmd[3] = {0x9d, 0xcd, index};
 int r = gchd_mail_write(d, 0x33, cmd, sizeof(cmd));
 if (r)
  return r;
 return gchd_mail_read(d, 0x33, value, 1);
}

