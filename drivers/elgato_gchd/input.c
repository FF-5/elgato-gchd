 r = gchd_mail_write(d, GCHD_MAIL_PORT_SYSTEM, (u8[]){GCHD_CMD_REGISTER_READ,GCHD_CMD_REGISTER_READ_EXT,GCHD_VALUE_64}, 3); if (r) return r;
