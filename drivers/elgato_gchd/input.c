static int gchd_mode_regs(struct gchd *d)
{
 int r;
 u16 w = d->input_width, h = d->input_height;
 u16 profile = 1; /* original v_h264_profile default: Main */

 if (w >= 1920) {
  if ((r = gchd_sparam(d, 0x152c, 0, 16, w))) return r;
  if ((r = gchd_sparam(d, 0x152e, 0, 16, h))) return r;
 } else if (w >= 1280) {
  if ((r = gchd_sparam(d, 0x152c, 0, 16, 1280))) return r;
  if ((r = gchd_sparam(d, 0x152e, 0, 16, 720))) return r;
 } else {
  if ((r = gchd_sparam(d, 0x152c, 0, 16, 720))) return r;
  if ((r = gchd_sparam(d, 0x152e, 0, 16, 480))) return r;
 }
 if ((r = gchd_sparam(d, 0x1526, 0, 8, d->h264_level ? d->h264_level : 41))) return r;
 if ((r = gchd_sparam(d, 0x1526, 8, 8, d->h264_profile ? d->h264_profile : profile))) return r;
 if ((r = gchd_sparam(d, 0x1532, 0, 16, d->bitrate ? d->bitrate : 16000))) return r;
 return 0;
}

static int gchd_encoder_start(struct gchd *d)
{
 u8 reply[3];
 u8 magic[] = {0xab,0xa9,0x0f,0xa4,0x55};
 int r, i;
 u32 state;

 /*
  * This is the encoder bring-up sequence from the original configureDevice().
  * In particular, firmware load occurs after the 0x27f97b processor state and
  * before the four post-firmware readbacks.
  */
 /* Exact pre-encoder processor handshake from configureDevice(). */
 r = gchd_mail_write(d, 0x33, (u8[]){0xab,0xa9,0x0f,0xa4,0x55}, 5);
 if (r) return r;
 r = gchd_mail_read(d, 0x33, reply, 3);
 if (r) return r;

 for (i = 0; i < 1000; ++i) {
  r = gchd_mail_write(d, 0x33,
                      (u8[]){0xab,0xa9,0x0f,0xa4,0x55}, 5);
  if (r) return r;
  r = gchd_mail_read(d, 0x33, reply, 3);
  if (r) return r;
  /* 0x334455 means the processor is still coming up. */
  state = ((u32)reply[0] << 16) | ((u32)reply[1] << 8) | reply[2];
  if (state == 0x27f97b)
   break;
  if (state == 0x334455) {
   r = gchd_send_enable_state(d);
   if (r) return r;
   r = gchd_do_enable(d, BIT(2), d->input ? BIT(2) : 0);
   if (r) return r;
   r = gchd_do_enable(d, BIT(1), BIT(1));
   if (r) return r;
   continue;
  }
 }
 if (i == 1000)
  return -ETIMEDOUT;

 r = gchd_transcoder_init(d);
 if (r)
  return r;

 r = gchd_scmd(d, 4, 0x00, 0x0000);
 if (r)
  return r;

 r = gchd_load_encoder_firmware(d);
 if (r)
  return r;

 {
  u16 v;
  r = gchd_raw_read16(d, 0x0000, 0x0010, &v);
  if (r) return r;
  r = gchd_raw_read16(d, 0x0000, 0x0012, &v);
  if (r) return r;
  r = gchd_raw_read16(d, 0x0000, 0x0014, &v);
  if (r) return r;
  r = gchd_raw_read16(d, 0x0000, 0x0016, &v);
  if (r) return r;
 }

 /* Firmware can transiently return to 0x334455. */
 for (i = 0; i < 5; ++i) {
  r = gchd_mail_write(d, 0x33,
                      (u8[]){0xab,0xa9,0x0f,0xa4,0x5b}, 5);
  if (r) return r;
  r = gchd_mail_read(d, 0x33, reply, 3);
  if (r) return r;
  r = gchd_do_enable(d, BIT(2), 0);
  if (r) return r;
  state = ((u32)reply[0] << 16) | ((u32)reply[1] << 8) | reply[2];
  if ((state & 0xf8f0f0) == 0x78e040)
   break;
 }

 r = gchd_do_enable(d, BIT(3), BIT(3));
 if (r) return r;

 /* Turning on the encoder can temporarily return 0x334455. */
 for (i = 0; i < 1000; ++i) {
  r = gchd_mail_write(d, 0x33, magic, sizeof(magic));
  if (r) return r;
  r = gchd_mail_read(d, 0x33, reply, 3);
  if (r) return r;
  state = ((u32)reply[0] << 16) | ((u32)reply[1] << 8) | reply[2];
  if (state == 0x27f97b)
   break;
 }
 if (i == 1000)
  return -ETIMEDOUT;

 r = gchd_mail_write(d, 0x33, (u8[]){0x28,0x28}, 2);
 if (r) return r;
 r = gchd_mail_write(d, 0x33, (u8[]){0x29,0x89,0x5b}, 3);
 if (r) return r;
 r = gchd_mail_read(d, 0x33, reply, 1);
 if (r) return r;

 r = gchd_mail_write(d, 0x33, (u8[]){0xdd,0xce,0x3f,0xb2}, 4);
 if (r) return r;
 r = gchd_mail_read(d, 0x33, reply, 2);
 if (r) return r;

 r = gchd_do_enable(d, BIT(4), BIT(4));
 if (r) return r;

 for (i = 0; i < 1000; ++i) {
  r = gchd_mail_write(d, 0x33, (u8[]){0x43,0x23,0x84}, 3);
  if (r) return r;
  r = gchd_mail_read(d, 0x33, reply, 1);
  if (r) return r;
  if (reply[0] == 0xf7)
   break;
 }
 if (i == 1000)
  return -ETIMEDOUT;

 r = gchd_do_enable(d, BIT(4), 0);
 if (r) return r;

 r = gchd_mail_write(d, 0x33, (u8[]){0x89,0x89,0xfb}, 3);
 if (r) return r;
 r = gchd_mail_read(d, 0x33, reply, 1);
 if (r) return r;

 return 0;
}

static int gchd_read_9dcd(struct gchd *d, u8 index, u8 *value)
{
 u8 cmd[3] = {0x9d, 0xcd, index};
 int r = gchd_mail_write(d, 0x33, cmd, sizeof(cmd));
 if (r)
  return r;
 return gchd_mail_read(d, 0x33, value, 1);
}

